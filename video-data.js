export function findVideos({category, query = "", guideId} = {}) {
  const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  return helpVideos.filter(video => (!category || video.category === category) && (!guideId || video.guides.includes(guideId)) && terms.every(term => (video.title + " " + video.category).toLowerCase().includes(term)));
}
